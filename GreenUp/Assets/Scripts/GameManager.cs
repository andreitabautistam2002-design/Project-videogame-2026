using UnityEngine;

public class GameManager : MonoBehaviour
{
    // Singleton instance to access GameManager easily from other scripts
    public static GameManager Instance;

    [Header("Player Stats")]
    public int playerEnergy = 3;       // Initial player energy/lives
    public float sustainabilityScore = 0f; // Progress from 0% to 100%

    private void Awake()
    {
        if (Instance == null)
        {
            Instance = this;
        }
        else
        {
            Destroy(gameObject);
        }
    }

    // Method to increase sustainability progress when completing eco-actions
    // // Generated by AI (Assisted logic structure)
    public void AddSustainability(float amount)
    {
        sustainabilityScore += amount;
        sustainabilityScore = Mathf.Clamp(sustainabilityScore, 0f, 100f);
        Debug.Log("Sustainability Score: " + sustainabilityScore + "%");

        if (sustainabilityScore >= 100f)
        {
            TriggerVictory();
        }
    }

    // Method to decrease player energy when hitting a hazard
    public void TakeDamage(int damage)
    {
        playerEnergy -= damage;
        playerEnergy = Mathf.Clamp(playerEnergy, 0, 3);
        Debug.Log("Player Energy left: " + playerEnergy);

        if (playerEnergy <= 0)
        {
            TriggerGameOver();
        }
    }

    private void TriggerVictory()
    {
        Debug.Log("LEVEL COMPLETED - Victory!");
        // Logic for win UI or scene change can be added here
    }

    private void TriggerGameOver()
    {
        Debug.Log("GAME OVER - Player has no energy left.");
        // Logic for defeat UI or scene reload can be added here
    }
}