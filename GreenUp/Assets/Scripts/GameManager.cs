using UnityEngine;
using TMPro;

public class GameManager : MonoBehaviour
{
    public static GameManager Instance;

    [Header("Player Stats")]
    public int playerEnergy = 3;
    public float sustainabilityScore = 0f;

    [Header("Game Status UI")]
    [SerializeField] private TMP_Text statusText;

    [Header("Game Status Audio")]
    [SerializeField] private AudioSource statusAudio;
    [SerializeField] private AudioClip victorySound;
    [SerializeField] private AudioClip gameOverSound;

    private bool gameEnded = false;

    private void Awake()
    {
        if (Instance == null)
        {
            Instance = this;
        }
        else
        {
            Destroy(gameObject);
        }

        if (statusAudio == null)
        {
            statusAudio = GetComponent<AudioSource>();

            if (statusAudio == null)
            {
                statusAudio = gameObject.AddComponent<AudioSource>();
            }
        }

        statusAudio.playOnAwake = false;
        statusAudio.loop = false;
        statusAudio.spatialBlend = 0f;
    }

    // Generated by AI - Sustainability progress and victory condition
    public void AddSustainability(float amount)
    {
        if (gameEnded)
        {
            return;
        }

        sustainabilityScore += amount;
        sustainabilityScore = Mathf.Clamp(
            sustainabilityScore,
            0f,
            100f
        );

        Debug.Log(
            "Sustainability Score: "
            + sustainabilityScore
            + "%"
        );

        if (sustainabilityScore >= 100f)
        {
            TriggerVictory();
        }
    }

    // Decrease player energy when hitting a hazard
    public void TakeDamage(int damage)
    {
        if (gameEnded)
        {
            return;
        }

        playerEnergy -= damage;
        playerEnergy = Mathf.Clamp(
            playerEnergy,
            0,
            3
        );

        Debug.Log(
            "Player Energy left: "
            + playerEnergy
        );

        if (playerEnergy <= 0)
        {
            TriggerGameOver();
        }
    }

    private void TriggerVictory()
    {
        gameEnded = true;

        Debug.Log("LEVEL COMPLETED - Victory!");

        if (statusText != null)
        {
            statusText.text =
                "¡Nivel completado! Alcanzaste el 100% de sostenibilidad.";

            statusText.color =
                new Color32(0, 90, 45, 255);
        }

        PlayStatusSound(victorySound);
    }

    private void TriggerGameOver()
    {
        gameEnded = true;

        Debug.Log(
            "GAME OVER - Player has no energy left."
        );

        if (statusText != null)
        {
            statusText.text =
                "¡Sin energía! Debes cuidar mejor tus recursos.";

            statusText.color =
                new Color32(150, 0, 0, 255);
        }

        PlayStatusSound(gameOverSound);
    }

    private void PlayStatusSound(AudioClip clip)
    {
        if (statusAudio != null && clip != null)
        {
            statusAudio.PlayOneShot(clip);
        }
    }
}